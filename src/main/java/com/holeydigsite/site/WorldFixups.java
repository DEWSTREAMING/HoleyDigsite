package com.holeydigsite.site;

import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import com.holeydigsite.HoleyDigsite;
import net.minecraft.commands.arguments.blocks.BlockStateParser;
import net.minecraft.core.BlockPos;
import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.core.registries.Registries;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.server.MinecraftServer;
import net.minecraft.server.level.ServerLevel;
import net.minecraft.tags.BlockTags;
import net.minecraft.world.level.block.Block;
import net.minecraft.world.level.block.Blocks;
import net.minecraft.world.level.block.state.BlockState;

import java.io.Reader;
import java.util.ArrayList;
import java.util.HashSet;
import java.util.List;
import java.util.Optional;
import java.util.Set;

import org.jetbrains.annotations.Nullable;

/**
 * Phase 16.1: block fix-ups for parts of an existing world the mod never rebuilds - the island template outside the site zones
 * and owned plots. The data ({@code data/holeydigsite/world_fixups/<name>.json}) is generated by {@code tools/make_fixups.py}
 * as groups of "remove these blocks, place those"; coordinates are template coordinates, the island origin is the home site's
 * anchor minus {@code origin.offset}.
 *
 * <p>A group is applied only if its anchor blocks ({@code expect}: unchanged neighbours) and every expected non-leaf, non-plant
 * block are still where the old generator put them, and every
 * non-leaf target cell is free (air, a plant, or emptied by the group itself) - so anything a player changed is left alone.
 * Leaves and plants are handled leniently (a missing leaf is fine, a leaf that would land on a block is just not placed).</p>
 */
public final class WorldFixups {
    private WorldFixups() {}

    /** Outcome of one fix-up file on one island. */
    public record Result(int applied, int skipped, List<String> notes) {}

    /** Every shipped fix-up file, oldest first. A freshly built island gets all of them (see {@link #applyNewIsland}). */
    public static final List<String> ALL = List.of("floating_1_14_1", "slits_1_14_4", "signs_1_18_1");

    @Nullable
    private static JsonObject load(MinecraftServer server, String name) {
        ResourceLocation file = HoleyDigsite.id("world_fixups/" + name + ".json");
        Optional<net.minecraft.server.packs.resources.Resource> res = server.getResourceManager().getResource(file);
        if (res.isEmpty()) {
            HoleyDigsite.LOGGER.error("World fix-up {} not found", file);
            return null;
        }
        try (Reader r = res.get().openAsReader()) {
            return JsonParser.parseReader(r).getAsJsonObject();
        } catch (Exception e) {
            HoleyDigsite.LOGGER.error("Bad world fix-up {}", file, e);
            return null;
        }
    }

    /**
     * WorldVersion step (and {@code /holeydigsite site fixup}): applies {@code world_fixups/<name>.json} to every copy of the island in
     * every level. Returns the number of groups applied. Safe to run again: applied groups no longer match the old layout.
     */
    public static int applyAll(MinecraftServer server, String name) {
        JsonObject json = load(server, name);
        if (json == null) {
            return 0;
        }
        int applied = 0;
        for (ServerLevel level : server.getAllLevels()) {
            SiteData data = SiteData.getIfExists(level);
            if (data == null) {
                continue;
            }
            ResourceLocation site = ResourceLocation.parse(json.getAsJsonObject("origin").get("site").getAsString());
            for (SiteData.Site s : data.byId(site)) {
                applied += applyAt(level, s.anchor(), json, name).applied();
            }
        }
        return applied;
    }

    /**
     * A new island's home site was just built from its marker: apply every fix-up there too. A pack whose island template is older
     * than the mod (its config not updated) still gets a fixed island; with an up-to-date template nothing matches and nothing changes.
     */
    public static void applyNewIsland(ServerLevel level, ResourceLocation siteId, BlockPos anchor) {
        for (String name : ALL) {
            JsonObject json = load(level.getServer(), name);
            if (json != null && ResourceLocation.parse(json.getAsJsonObject("origin").get("site").getAsString()).equals(siteId)) {
                applyAt(level, anchor, json, name);
            }
        }
    }

    private static Result applyAt(ServerLevel level, BlockPos siteAnchor, JsonObject json, String name) {
        BlockPos origin = siteAnchor.subtract(pos(json.getAsJsonObject("origin").getAsJsonArray("offset")));
        Result r = apply(level, origin, json.getAsJsonArray("groups"));
        if (json.has("signs")) {
            Result sr = applySigns(level, origin, json.getAsJsonArray("signs"));
            r = new Result(r.applied() + sr.applied(), r.skipped() + sr.skipped(), concat(r.notes(), sr.notes()));
        }
        HoleyDigsite.LOGGER.info("World fix-up {} at island {}: {} groups applied, {} left alone {}", name, origin, r.applied(), r.skipped(), r.notes());
        return r;
    }

    /** Applies the groups with the island origin at {@code origin}. Public for tests. */
    public static Result apply(ServerLevel level, BlockPos origin, JsonArray groups) {
        int applied = 0, skipped = 0;
        List<String> notes = new ArrayList<>();
        for (JsonElement g : groups) {
            JsonObject o = g.getAsJsonObject();
            String why = applyGroup(level, origin, o);
            if (why == null) {
                applied++;
            } else {
                skipped++;
                notes.add(o.has("where") ? o.get("where").getAsString() + ": " + why : why);
            }
        }
        return new Result(applied, skipped, notes);
    }

    private static List<String> concat(List<String> a, List<String> b) {
        List<String> l = new ArrayList<>(a);
        l.addAll(b);
        return l;
    }

    /**
     * Phase 20.1: sign text changes ({@code "signs": [{pos, block, old[4], new[4]}]}, template coordinates). A sign is rewritten only if the
     * block there is still that sign and its four front lines still read exactly {@code old}; a player-edited or removed sign is left alone.
     * Public for tests.
     */
    public static Result applySigns(ServerLevel level, BlockPos origin, JsonArray signs) {
        int applied = 0, skipped = 0;
        List<String> notes = new ArrayList<>();
        for (JsonElement e : signs) {
            JsonObject o = e.getAsJsonObject();
            BlockPos p = origin.offset(pos(o.getAsJsonArray("pos")));
            level.getChunk(p);
            String why = null;
            if (!level.getBlockState(p).is(BuiltInRegistries.BLOCK.get(ResourceLocation.parse(o.get("block").getAsString())))
                    || !(level.getBlockEntity(p) instanceof net.minecraft.world.level.block.entity.SignBlockEntity sign)) {
                why = "no sign at " + p;
            } else {
                net.minecraft.world.level.block.entity.SignText text = sign.getFrontText();
                JsonArray old = o.getAsJsonArray("old");
                JsonArray now = o.getAsJsonArray("new");
                for (int i = 0; i < 4 && why == null; i++) {
                    if (!text.getMessage(i, false).getString().equals(old.get(i).getAsString())) {
                        why = "sign edited at " + p;
                    }
                }
                if (why == null) {
                    for (int i = 0; i < 4; i++) {
                        text = text.setMessage(i, net.minecraft.network.chat.Component.literal(now.get(i).getAsString()));
                    }
                    sign.setText(text, true);
                    sign.setChanged();
                    level.sendBlockUpdated(p, sign.getBlockState(), sign.getBlockState(), Block.UPDATE_CLIENTS);
                }
            }
            if (why == null) {
                applied++;
            } else {
                skipped++;
                notes.add(why);
            }
        }
        return new Result(applied, skipped, notes);
    }

    private static boolean lenient(BlockState s) {
        return s.is(BlockTags.LEAVES) || s.is(BlockTags.REPLACEABLE) || s.is(BlockTags.FLOWERS) || s.is(Blocks.LIGHT);
    }

    /** null = applied, else why the group was left alone. */
    private static String applyGroup(ServerLevel level, BlockPos origin, JsonObject o) {
        if (o.has("expect")) {
            for (JsonElement e : o.getAsJsonArray("expect")) {
                JsonArray a = e.getAsJsonArray();
                BlockPos p = origin.offset(a.get(0).getAsInt(), a.get(1).getAsInt(), a.get(2).getAsInt());
                level.getChunk(p);
                if (!level.getBlockState(p).is(BuiltInRegistries.BLOCK.get(ResourceLocation.parse(a.get(3).getAsString())))) {
                    return "not the old layout at " + p + " (" + level.getBlockState(p).getBlock() + ")";
                }
            }
        }
        List<BlockPos> remove = new ArrayList<>();
        Set<BlockPos> freed = new HashSet<>();
        for (JsonElement e : o.getAsJsonArray("remove")) {
            JsonArray a = e.getAsJsonArray();
            BlockPos p = origin.offset(a.get(0).getAsInt(), a.get(1).getAsInt(), a.get(2).getAsInt());
            Block expected = BuiltInRegistries.BLOCK.get(ResourceLocation.parse(a.get(3).getAsString()));
            level.getChunk(p);
            BlockState now = level.getBlockState(p);
            if (now.is(expected)) {
                remove.add(p);
                freed.add(p);
            } else if (!lenient(expected.defaultBlockState())) {
                return "changed at " + p + " (" + now.getBlock() + ")";
            }
        }
        List<BlockPos> placeAt = new ArrayList<>();
        List<BlockState> placeState = new ArrayList<>();
        for (JsonElement e : o.getAsJsonArray("place")) {
            JsonArray a = e.getAsJsonArray();
            BlockPos p = origin.offset(a.get(0).getAsInt(), a.get(1).getAsInt(), a.get(2).getAsInt());
            BlockState st;
            try {
                st = BlockStateParser.parseForBlock(level.holderLookup(Registries.BLOCK), a.get(3).getAsString(), false).blockState();
            } catch (Exception ex) {
                return "bad state " + a.get(3).getAsString();
            }
            level.getChunk(p);
            BlockState now = level.getBlockState(p);
            boolean free = now.isAir() || lenient(now) || freed.contains(p);
            if (!free) {
                if (lenient(st)) {
                    continue;       // a leaf would land on something: just leave it out
                }
                return "occupied at " + p + " (" + now.getBlock() + ")";
            }
            placeAt.add(p);
            placeState.add(st);
        }
        for (BlockPos p : remove) {
            level.setBlock(p, Blocks.AIR.defaultBlockState(), Block.UPDATE_CLIENTS);
        }
        for (int i = 0; i < placeAt.size(); i++) {
            level.setBlock(placeAt.get(i), placeState.get(i), Block.UPDATE_CLIENTS);
        }
        return null;
    }

    private static BlockPos pos(JsonArray a) {
        return new BlockPos(a.get(0).getAsInt(), a.get(1).getAsInt(), a.get(2).getAsInt());
    }
}
